"""Tests for data.newsapi_feed.

The module wraps the NewsAPI /everything endpoint, normalises article dicts,
deduplicates them by URL, filters by published-at age, and caches results
via CacheManager (JSON sidecar). All network/HTTP is mocked — no real
NewsAPI traffic is generated by these tests.

Branches pinned:

  - SHIPPING_QUERIES configuration
      * Exactly three query specs, each with q/sortBy/language/pageSize keys
      * Every q is a non-empty string

  - _get_api_key / newsapi_available
      * Returns env var when Streamlit secrets absent
      * Returns empty string when nothing configured
      * newsapi_available() reflects bool(_get_api_key())
      * Streamlit secrets access exception is swallowed (falls through to env)

  - _cache_key / _cache_path
      * Stable, date-bearing key format ``newsapi_shipping_<YYYY-MM-DD>``
      * Resulting path nests under ``<cache_dir>/newsapi/`` with .json suffix
      * Slugified filename matches CacheManager._slugify of the key

  - _load_json_cache
      * Missing file → returns None
      * Fresh file → returns the parsed list of dicts
      * Stale file (older than ttl) → returns None
      * Corrupt JSON → returns None and does not raise

  - _save_json_cache
      * Creates the parent directory and writes a valid JSON list
      * datetime values are serialised via default=str (no TypeError)

  - _parse_published_at
      * Z-suffixed ISO string → tz-aware UTC datetime
      * Naive ISO string → assumed UTC
      * Missing / None input → defaults to "now" in UTC
      * Malformed string → defaults to "now" in UTC
      * Non-string (int) → defaults to "now" in UTC

  - _normalise_article
      * Happy path → all fields present, content truncated to 500 chars
      * Empty content falls back to description (also capped at 500)
      * Whitespace-only fields are stripped
      * Title containing "[Removed]" → None
      * Description containing "[Removed]" → None
      * Missing title → None
      * Missing url → None
      * Missing/None source dict → source_name == ""

  - _request_query (requests.get monkeypatched)
      * Network error (RequestException) → []
      * HTTP 401 → []
      * HTTP 500 → []
      * Non-JSON 200 body → []
      * 200 with status != "ok" → []
      * 200 with status "ok" → list of articles from payload
      * 200 with no "articles" key → []
      * HTTP 429 raises _RateLimitError (tenacity wires retry behaviour)

  - fetch_newsapi_articles  (public API; all HTTP mocked, tmp_path cache)
      * Missing API key → returns []
      * Cache hit → reads cached JSON, no HTTP issued, respects max_articles
      * Cache miss → invokes the HTTP layer once per query and writes cache
      * Articles are deduplicated by URL across queries
      * Articles older than ``from_days_back`` are filtered out
      * Result is sorted newest-first
      * ``max_articles`` caps the final list size
      * Empty fetch returns [] and does not write a cache file
      * [Removed] articles are filtered out end-to-end
"""
from __future__ import annotations

