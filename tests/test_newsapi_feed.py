# ─── Helpers ────────────────────────────────────────────────────────────────


class _FakeResponse:
    """Minimal stand-in for requests.Response."""

    def __init__(self, status_code: int = 200, payload=None, raise_json: bool = False):
        self.status_code = status_code
        self._payload = payload if payload is not None else {}
        self._raise_json = raise_json

    def json(self):
        if self._raise_json:
            raise ValueError("not json")
        return self._payload


def _make_article(
    *,
    title: str = "Container rates surge across transpacific",
    url: str = "https://example.com/a1",
    description: str = "Spot rates climbed sharply this week.",
    content: str = "Some article body.",
    author: str = "Jane Doe",
    source: str = "Reuters",
    published_at: str = "2026-05-20T12:00:00Z",
) -> dict:
    """Build a raw NewsAPI-shaped article dict."""
    return {
        "title":       title,
        "url":         url,
        "description": description,
        "content":     content,
        "author":      author,
        "source":      {"name": source} if source is not None else None,
        "publishedAt": published_at,
    }


def _ok_payload(articles: list[dict]) -> dict:
    return {"status": "ok", "totalResults": len(articles), "articles": articles}


def _set_api_key(monkeypatch, value: str = "TEST_KEY_DUMMY") -> None:
    """Ensure _get_api_key() returns ``value`` — bypasses Streamlit secrets."""
    monkeypatch.setattr(nf, "_get_api_key", lambda: value, raising=True)


