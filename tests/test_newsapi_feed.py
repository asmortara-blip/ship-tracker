def test_fetch_empty_does_not_write_cache(monkeypatch, tmp_path):
    """All three queries return empty → no cache file persisted."""
    _set_api_key(monkeypatch)
    cache = CacheManager(tmp_path)
    monkeypatch.setattr(nf.time, "sleep", lambda *_a, **_kw: None)

    monkeypatch.setattr(
        nf.requests, "get",
        lambda *a, **kw: _FakeResponse(status_code=200,
                                       payload=_ok_payload([])),
    )

    out = nf.fetch_newsapi_articles(cache=cache, cache_ttl_hours=2.0)
    assert out == []

    date_str = datetime.now(tz=timezone.utc).strftime("%Y-%m-%d")
    cache_file = nf._cache_path(cache, date_str)
    assert not cache_file.exists()
