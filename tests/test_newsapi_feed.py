def test_fetch_returns_cached_payload_on_hit(monkeypatch, tmp_path):
    _set_api_key(monkeypatch)
    cache = CacheManager(tmp_path)

    # Seed the cache file for today's date.
    date_str = datetime.now(tz=timezone.utc).strftime("%Y-%m-%d")
    cached = [{"title": f"cached-{i}", "url": f"u{i}"} for i in range(5)]
    path = nf._cache_path(cache, date_str)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(cached), encoding="utf-8")

    # If HTTP is hit, the test should fail.
