def test_save_json_cache_handles_datetime_via_default_str(tmp_path):
    """published_at is a datetime in normalised dicts — must serialise."""
    p = tmp_path / "newsapi" / "x.json"
    dt = datetime(2026, 5, 20, 12, 0, tzinfo=timezone.utc)
    articles = [{"title": "t", "url": "u", "published_at": dt}]
    nf._save_json_cache(p, articles)  # must not raise
    loaded = json.loads(p.read_text(encoding="utf-8"))
    assert isinstance(loaded[0]["published_at"], str)
    assert "2026-05-20" in loaded[0]["published_at"]


